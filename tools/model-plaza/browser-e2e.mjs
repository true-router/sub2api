// Run with: ego-browser nodejs < tools/model-plaza/browser-e2e.mjs
// Start fixture-server.mjs first. This exercises the actual built Vue route.
const fs = await import('node:fs/promises')
const out = '/tmp/sub2api-model-plaza-e2e'
await fs.mkdir(out, { recursive: true })
const task = await taskSpace('sub2api-model-plaza-e2e')
const page = task.page('p1')
const origin = 'http://127.0.0.1:4317'
const checks = []
function check(name, pass, evidence) { checks.push({ name, pass, evidence }); if (!pass) throw new Error(name + ': ' + evidence) }
async function text() { return page.evaluate(() => document.body.innerText) }
async function scenario(name) {
  await fetch(`${origin}/__fixture?scenario=${name}`)
  await page.goto(`${origin}/model-plaza`)
  await page.waitForSelector('[data-model]')
}
try {
  await page.goto(origin)
  await page.evaluate(() => localStorage.setItem('sub2api_locale', 'zh'))
  await scenario('standard')
  let body = await text()
  check('CNY prices include recharge benefit', body.includes('¥6.40') && body.includes('¥56.00') && body.includes('88.6%'), body)
  check('Output price is converted', body.includes('¥32.00') && body.includes('¥280.00'), body)
  await page.click('[data-testid="currency-switch"] [role="radio"]:nth-of-type(2)')
  body = await text()
  check('USD changes both prices, preserves savings', body.includes('US$0.91') && body.includes('US$8.00') && body.includes('88.6%'), body)
  await page.click('[data-testid="offer-details"] summary')
  body = await text()
  check('Cache and peak disclosures', body.includes('缓存') && body.includes('18:00'), body)
  await page.fill('input[type="search"]', 'no-such-model')
  check('Search empties catalog', (await text()).includes('没有匹配的模型'), await text())
  await scenario('user-rate')
  check('User rate replaces group rate', (await text()).includes('¥4.00'), await text())
  await scenario('missing-rate')
  body = await text()
  check('No fabricated savings without FX', !body.includes('88.6%') && body.includes('汇率暂不可用'), body)
  await scenario('missing-official')
  check('No fabricated official price', !(await text()).includes('88.6%'), await text())
  await scenario('no-discount')
  check('No discount claim for a premium price', !(await text()).includes('节省 '), await text())
  await scenario('subscription')
  check('Subscription never claims per-token cash savings', !(await text()).includes('88.6%'), await text())
  await scenario('tiers')
  await page.click('[data-testid="offer-details"] summary')
  body = await text()
  check('Context and time pricing remain visible', body.includes('200K') && body.includes('Asia/Shanghai'), body)
  await scenario('tiny')
  check('Positive tiny prices are not free', (await text()).includes('0.0000008'), await text())
  await scenario('stale-rate')
  check('Cached FX is disclosed', (await text()).includes('缓存汇率'), await text())
  await scenario('standard')
  await page.cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  check('Mobile has no horizontal page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '390px')
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  check('Dark mode uses semantic surfaces', await page.evaluate(() => getComputedStyle(document.querySelector('[data-testid="plaza-catalog"] article')).backgroundColor !== 'rgb(255, 255, 255)'), 'dark model card')
  console.log(JSON.stringify({ checks: checks.map(({name,pass}) => ({name,pass})) }))
  await scenario('standard')
  await page.waitForSelector('[data-testid="price-chart"] canvas')
  const chart = await page.evaluate(() => { const c = document.querySelector('[data-testid="price-chart"]'); return { ours: Number(c.dataset.ourValue), official: Number(c.dataset.officialValue) } })
  check('Chart uses actual comparable CNY values', Math.abs(chart.ours - 6.4) < 1e-9 && chart.official === 56, chart)
  await page.click('[data-testid="metric-output"]')
  check('Output chart uses output prices', await page.evaluate(() => Math.abs(Number(document.querySelector('[data-testid="price-chart"]').dataset.ourValue) - 32) < 1e-9), await text())
  await scenario('different-output')
  await page.click('[data-testid="metric-output"]')
  check('Output savings are independently calculated', (await text()).includes('82.9%'), await text())
  await scenario('missing-rate')
  check('No chart for incomparable currencies', await page.evaluate(() => !document.querySelector('[data-testid="price-chart"] canvas')), await text())
  await scenario('demo')
  await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1100, deviceScaleFactor: 1, mobile: false })
  await page.evaluate(() => document.documentElement.classList.remove('dark'))
  const cards = await page.evaluate(() => Array.from(document.querySelectorAll('[data-model]')).map(n => { const r = n.getBoundingClientRect(); return { model: n.dataset.model, x: r.x, y: r.y, width: r.width, height: r.height } }))
  check('Desktop uses two model cards per row', cards.length === 3 && Math.abs(cards[0].y - cards[1].y) < 2 && cards[0].x !== cards[1].x, cards)
  await page.click('[data-model="claude-fable-5-2"] [data-offer-id="2"]')
  check('Card group selection recalculates price and chart', await page.evaluate(() => Math.abs(Number(document.querySelector('[data-model="claude-fable-5-2"] [data-testid="price-chart"]').dataset.ourValue) - 4.8) < 1e-9), await text())
  await page.screenshot({ path: `${out}/cards-desktop.png`, fullPage: true })
  await page.cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  check('Card charts fit phone width', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '390px card grid')
  await page.screenshot({ path: `${out}/cards-mobile.png`, fullPage: true })
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.screenshot({ path: `${out}/cards-mobile-dark.png`, fullPage: true })
  console.log(JSON.stringify({ cardChecks: checks.slice(15).map(({name,pass}) => ({name,pass})) }))
  await task.finish({ keep: [] })
} finally {
  await fetch(`${origin}/__fixture?scenario=demo`)
  await fs.writeFile(`${out}/receipt.json`, JSON.stringify({ generated_at: new Date().toISOString(), scope: 'Built frontend route with deterministic API fixtures; not live backend acceptance', checks }, null, 2))
}
