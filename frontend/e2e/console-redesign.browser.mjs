async function api(path, method='GET', body) {
  return page.evaluate(async ({path,method,body}) => {
    const r = await fetch('/api/v1'+path, {method,headers:{Authorization:'Bearer '+localStorage.getItem('auth_token'),'Content-Type':'application/json'},...(body ? {body:JSON.stringify(body)} : {})})
    return {status:r.status,...await r.json()}
  },{path,method,body})
}
