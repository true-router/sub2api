const fs = await import('node:fs/promises')
const task = await taskSpace('TrueRouter home redesign')
const page = task.page('p1')
const output = "__ARTIFACT_DIRECTORY__"
const checks = []
const check = (name, passed) => { checks.push({ name, passed: Boolean(passed) }); if (!passed) throw new Error(name); console.log('PASS ' + name) }
const settings = async value => {
  const response = await page.fetch('/api/v1/__home_fixture', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(value) })
  if (!response.ok) throw new Error('Fixture update failed')
  await page.goto('http://127.0.0.1:13037/home')
  await page.waitForSelector('.home-page, #custom-home, iframe')
}
const shot = async name => {
  const result = await page.cdp('Page.captureScreenshot', { format: 'png', captureBeyondViewport: true })
  await fs.writeFile(output + '/' + name + '.png', Buffer.from(result.data, 'base64'))
}
const overflow = () => document.documentElement.scrollWidth <= innerWidth
try {
  await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false })
  await page.goto('http://127.0.0.1:13037/home')
  await page.evaluate(() => { localStorage.removeItem('auth_token'); localStorage.removeItem('auth_user'); localStorage.setItem('sub2api_locale', 'zh'); localStorage.setItem('theme', 'light') })
  await page.reload()
  await page.waitForSelector('[data-testid="compact-home"]')
  check('Compact home retains site subtitle and anonymous login destination', await page.evaluate(() => document.body.textContent.includes('满血 AI，不掺一滴水') && document.querySelector('[data-testid="home-primary-action"]').getAttribute('href') === '/login' && document.querySelectorAll('main article').length === 0))
  check('Public model plaza remains available', await page.evaluate(() => !!document.querySelector('a[href="/model-plaza"]')))
  check('Compact home has no quick-start links or SDK panel', await page.evaluate(() => !document.querySelector('#integration, a[href="#integration"], #home-code, [role="tab"]') && !document.body.textContent.includes('快速接入')))
  check('Desktop has no horizontal overflow', await page.evaluate(overflow))
  await shot('home-desktop')
  await page.click('[data-testid="home-primary-action"]')
  await page.waitForURL('**/login')
  check('Primary action opens login', true)
  await page.goto('http://127.0.0.1:13037/home')
  await page.waitForSelector('[data-testid="compact-home"]')
  await page.click('button[aria-label="切换到深色模式"]')
  await page.reload()
  await page.waitForSelector('button[aria-label="切换到浅色模式"]')
  check('Dark mode persists on reload', await page.evaluate(() => document.documentElement.classList.contains('dark') && getComputedStyle(document.querySelector('.home-page')).backgroundColor === 'rgb(18, 18, 18)'))
  await shot('home-dark')
  await page.click('button[aria-label="切换到浅色模式"]')
  await page.click('button[title="中文"]')
  await page.click('button:has-text("English")')
  await page.waitForFunction(() => document.querySelector('h1')?.textContent.includes('One API.'))
  check('Locale switch translates the landing content', true)
  await shot('home-english')
  await page.evaluate(() => localStorage.setItem('sub2api_locale', 'zh'))
  await settings({ model_plaza_require_auth: true })
  await page.waitForSelector('[data-testid="compact-home"]')
  check('Anonymous visitors cannot see the private model plaza', await page.evaluate(() => !document.querySelector('a[href="/model-plaza"]')))
  await settings({ model_plaza_enabled: false, api_base_url: '' })
  check('Disabled model plaza stays hidden without a quick-start fallback', await page.evaluate(() => !document.querySelector('a[href="/model-plaza"], a[href="#integration"]')))
  await settings({ compact_home_enabled: false })
  await page.waitForSelector('[data-testid="full-home"]')
  check('Full home also excludes quick start', await page.evaluate(() => !document.querySelector('#integration, a[href="#integration"], #home-code')))
  check('Full home renders three capability cards', await page.evaluate(() => document.querySelectorAll('main article').length === 3))
  await shot('home-full')
  for (const width of [390, 320]) {
    await page.cdp('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: true })
    await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth)
    check(`Full mobile home at ${width}px has no horizontal overflow`, await page.evaluate(overflow))
    await shot('home-mobile-' + width)
  }
  await settings({ site_name: 'A'.repeat(120), site_subtitle: 'B'.repeat(240), api_base_url: 'https://api.example.test/' + 'c'.repeat(180), compact_home_enabled: true })
  check('Long site settings do not overflow narrow compact home', await page.evaluate(overflow))
  await settings({ home_content: '<section id="custom-home">Custom home</section>' })
  await page.waitForSelector('#custom-home')
  check('Custom HTML takes precedence over compact mode', await page.evaluate(() => !document.querySelector('.home-page')))
  await settings({ home_content: 'http://127.0.0.1:13037/logo.svg' })
  await page.waitForSelector('iframe')
  check('Custom URL takes precedence and has an accessible title', await page.evaluate(() => document.querySelector('iframe').title === 'TrueRouter' && !document.querySelector('.home-page')))
  await settings({ model_plaza_require_auth: true })
  await page.evaluate(() => { localStorage.setItem('auth_token', 'local-member-preview'); localStorage.setItem('auth_user', JSON.stringify({ id: 2, role: 'user', email: 'member1@example.test' })) })
  await page.reload()
  await page.waitForSelector('[data-testid="home-primary-action"][href="/dashboard"]')
  check('Members receive their dashboard destination and private model plaza', await page.evaluate(() => !!document.querySelector('a[href="/model-plaza"]')))
  await page.evaluate(() => { localStorage.setItem('auth_token', 'local-preview-only'); localStorage.setItem('auth_user', JSON.stringify({ id: 1, role: 'admin', email: 'admin@example.test' })) })
  await page.reload()
  await page.waitForSelector('[data-testid="home-primary-action"][href="/admin/dashboard"]')
  check('Administrators receive their dashboard destination', true)
  await settings({})
  await page.evaluate(() => { localStorage.removeItem('auth_token'); localStorage.removeItem('auth_user') })
  await page.cdp('Emulation.clearDeviceMetricsOverride')
  await page.reload()
  await task.finish({ keep: [] })
} finally {
  await fs.writeFile(output + '/checks.json', JSON.stringify({ checks, fixture: true, origin: 'http://127.0.0.1:13037', rerun: 'cd frontend && node e2e/home.mjs' }, null, 2))
}
