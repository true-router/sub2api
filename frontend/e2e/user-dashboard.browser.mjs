await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false })
await wait(() => innerWidth === 1440 && document.querySelector('.sidebar').getBoundingClientRect().left >= 0 && document.querySelectorAll('main canvas').length === 2)
