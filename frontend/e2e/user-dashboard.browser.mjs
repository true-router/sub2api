const fs = await import('node:fs/promises')
const task = await taskSpace('truerouter-user-dashboard')
const page = task.page('p1')
const output = "__ARTIFACT_DIRECTORY__"
const checks = []
const check = (name, passed) => { checks.push({ name, passed: Boolean(passed) }); if (!passed) throw new Error(name); console.log('PASS ' + name) }
const read = async fn => {
  const result = await page.cdp('Runtime.evaluate', { expression: '(' + fn.toString() + ')()', returnByValue: true })
  if (result.exceptionDetails) throw new Error(result.exceptionDetails.text)
  return result.result.value
}
const wait = async fn => {
  for (let i = 0; i < 200; i++) { if (await read(fn)) return; await new Promise(resolve => setTimeout(resolve, 50)) }
  throw new Error('Dashboard did not reach the expected state')
}
const shot = async name => {
  const result = await page.cdp('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false })
  await fs.writeFile(output + '/' + name + '.png', Buffer.from(result.data, 'base64'))
}
await page.cdp('Emulation.clearDeviceMetricsOverride')
await page.goto('http://127.0.0.1:13035/login')
await page.evaluate(() => {
  localStorage.setItem('auth_token', 'local-member-preview')
  localStorage.setItem('auth_user', JSON.stringify({ id: 2, role: 'user', email: 'member1@example.test', balance: 100 }))
  localStorage.setItem('sub2api_locale', 'zh')
  localStorage.setItem('theme', 'light')
  localStorage.setItem('user_guide_2_user_v4_interactive', 'true')
})
await page.goto('http://127.0.0.1:13035/dashboard')
await page.waitForSelector('[data-testid="user-dashboard-stats"]')
await page.keyboard.press('Escape')
await page.waitForSelector('[data-testid="dashboard-recent-usage"] table tbody tr')
check('Account workspace uses BoardUI and hides administrator links', await page.evaluate(() => document.documentElement.dataset.adminUi === 'boardui' && !document.querySelector('.sidebar a[href^="/admin"]') && !document.querySelector('.app-content > .app-header')))
check('Eight shared statistic cards and five recent records render', await page.evaluate(() => document.querySelectorAll('[data-testid="user-dashboard-stats"] [data-boardui="stat-card"]').length === 8 && document.querySelectorAll('[data-testid="dashboard-recent-usage"] tbody tr').length === 5))
check('Usage and quota cards retain platform breakdown and disabled limits', await page.evaluate(() => document.querySelector('[data-platform="anthropic"]').textContent.includes('禁用') && !!document.querySelector('[data-platform="__other__"]')))
check('Both charts render real datasets', await page.evaluate(() => document.querySelectorAll('main canvas').length === 2))
await page.click('main [role="radiogroup"] [role="radio"][aria-checked="true"]')
await page.press('main [role="radiogroup"] [role="radio"][aria-checked="true"]', 'ArrowRight')
await page.waitForFunction(() => [...document.querySelectorAll('main [role="radio"]')].some(e => e.textContent.includes('小时') && e.getAttribute('aria-checked') === 'true'))
check('Granularity supports keyboard selection', true)
await page.click('main .date-picker-trigger')
