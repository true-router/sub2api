await page.click('.date-picker-apply')
await page.waitForFunction(() => !document.querySelector('.date-picker-dropdown') && document.querySelectorAll('main canvas').length === 2)
await page.click('main button:text-is("按实际消费")')
check('Model distribution metric changes', await page.evaluate(() => [...document.querySelectorAll('main button')].find(e => e.textContent.trim() === '按实际消费')?.classList.contains('shadow-sm')))
await page.click('[data-testid="user-dashboard-refresh"]')
await page.waitForFunction(() => !document.querySelector('[data-testid="user-dashboard-refresh"]').disabled && document.querySelectorAll('main canvas').length === 2)
check('Refresh retains the dashboard and reloads the data', await page.evaluate(() => !!document.querySelector('[data-testid="user-dashboard-stats"]') && !document.querySelector('main [role="alert"]')))
