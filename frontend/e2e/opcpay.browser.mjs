// Run only against opcpay-preview.mjs and the simulated-provider E2E backend.
const fs = await import('node:fs/promises')
const task = await taskSpace('sub2api-opcpay-recharge-cards')
const page = task.page('p1')
const origin = 'http://127.0.0.1:13034'
const output = "__OPCPAY_ARTIFACT_DIRECTORY__"
await fs.mkdir(output, { recursive: true })
const checks = []
function check(name, passed) {
  checks.push({ name, passed })
  if (!passed) throw new Error(name)
}
await page.goto(origin + '/login')
const login = await page.fetch('/api/v1/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'admin', password: 'admin' }) })
const { data } = typeof login.body === 'string' ? JSON.parse(login.body) : login.body
await page.evaluate(({ access_token, user }) => {
  localStorage.setItem('auth_token', access_token)
  localStorage.setItem('auth_user', JSON.stringify(user))
  localStorage.setItem('sub2api_locale', 'zh')
  localStorage.setItem('theme', 'light')
  localStorage.setItem('admin_guide_1_admin_v4_interactive', 'true')
}, data)
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
await page.goto(origin + '/admin/settings')
await page.waitForSelector('loc=role:tab[name="支付设置"]', { timeout: 15000 })
console.log(await page.snapshot())
await page.click('loc=role:tab[name="支付设置"]')
await page.waitForSelector('text=一人付充值卡')
check('设置页显示一人付服务商', true)
await page.click('loc=role:button[name="编辑"]')
await page.waitForSelector('input[aria-label="API Key"]')
const keyField = await page.evaluate(() => {
  const input = document.querySelector('input[aria-label="API Key"]')
  const dialog = document.querySelector('[role="dialog"]')
  return { type: input.type, blank: input.value === '', refund: dialog.innerText.includes('允许退款') }
})
check('密钥不回显且使用密码输入框', keyField.type === 'password' && keyField.blank)
check('一人付不显示退款开关', !keyField.refund)
await page.screenshot({ path: output + '/provider-settings.png' })
await page.click('loc=role:button[name="保存"]')
await page.waitForSelector('loc=role:dialog[name="编辑服务商"]', { state: 'hidden', timeout: 15000 })
await page.goto(origin + '/purchase')
await page.waitForFunction(() => document.querySelectorAll('[data-testid="opcpay-card"]').length === 2, undefined, { timeout: 15000 })
console.log(await page.snapshot())
const cards = await page.evaluate(() => [...document.querySelectorAll('[data-testid="opcpay-card"]')].map(card => card.innerText))
check('显示两张充值卡的实际售价和数量', cards[0].includes('9.90') && cards[0].includes('10 USD') && cards[1].includes('18.80') && cards[1].includes('20 USD'))
await page.click('[data-testid="opcpay-card"] >> nth=1')
await page.waitForSelector('loc=role:button[name="支付宝购买 · CNY 18.80"]')
check('选择充值卡后显示对应购买价格', true)
await page.screenshot({ path: output + '/recharge-cards.png' })
await page.click('loc=role:button[name="支付宝购买 · CNY 18.80"]')
await page.waitForSelector('img[alt="支付宝购买入口二维码"]', { timeout: 15000 })
check('生成所选充值卡的购买二维码', true)
await page.click('loc=role:button[name="我已购买，确认充值"]')
await page.waitForFunction(() => document.body.innerText.includes('充值完成。已核销 20 积分，增加 20 USD 余额。'), undefined, { timeout: 15000 })
check('确认充值按所选卡显示20积分和20USD到账结果', true)
check('仅有充值卡时隐藏不可用的旧金额表单', !(await page.evaluate(() => document.body.innerText.includes('充值功能暂未开放'))))
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
await page.waitForFunction(() => innerWidth === 390 && document.documentElement.scrollWidth <= document.documentElement.clientWidth, undefined, { timeout: 10000 })
check('移动端没有横向溢出', !(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)))
await page.screenshot({ path: output + '/recharge-mobile.png' })
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
await page.click('loc=role:button[name="深色模式"]')
await page.waitForFunction(() => document.documentElement.classList.contains('dark'))
await page.screenshot({ path: output + '/recharge-dark.png' })
check('充值卡区域切换到深色主题', true)
await fs.writeFile(output + '/checks.json', JSON.stringify(checks, null, 2))
console.log({ passed: checks.length, failed: 0, mode: 'simulated-provider-synthetic-session' })
await task.finish({ keep: [] })
